/* ================================================================
 *  RingBuf_Poll — 主循环消费一帧并回调解析函数
 *
 *  每次调用最多消费一帧, 队列空时直接返回 (零开销热路径)
 *  在回调用户函数前关中断拷贝数据, 防止 ISR 并发 Push 导致数据撕裂
 * ================================================================ */
void RingBuf_Poll(void)
{
    if (rb_count == 0 || rb_handler == 0) return;

    /* 关中断拷贝帧数据 (防止 ISR Push 干扰) */
    char frame[RINGBUF_FRAME_LEN];
    __disable_irq();
    memcpy(frame, rb_queue[rb_tail].data, RINGBUF_FRAME_LEN);
    rb_tail = (rb_tail + 1) % RINGBUF_CAPACITY;
    rb_count--;
    __enable_irq();

    /* 回调用户解析函数 (主循环上下文, 安全) */
    rb_handler(frame);
}
