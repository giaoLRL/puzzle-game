#include "../protocol/ringbuf.h"
#include <string.h>

/* ========== 内部类型 ========== */
/* 环形队列帧槽位 */
typedef struct {
    char  data[RINGBUF_FRAME_LEN];
} FrameSlot;

/* ========== 内部状态 ========== */
static RingBuf_FrameHandler  rb_handler = 0;          /* 用户回调函数指针 */

/* 环形队列 (单生产者 ISR / 单消费者 主循环) */
static volatile uint8  rb_head  = 0;                  /* ISR 写入位置 */
static volatile uint8  rb_tail  = 0;                  /* 主循环读取位置 */
static volatile uint8  rb_count = 0;                  /* 当前帧数 */
static          FrameSlot rb_queue[RINGBUF_CAPACITY]; /* 帧存储区 */

/* 字节拼接器 (ISR 中使用, 拼满一帧就入队) */
static volatile uint8  rb_recv_idx = 0;               /* 拼接缓冲区写入位置 */
static          char   rb_recv_buf[RINGBUF_FRAME_LEN];/* 拼接缓冲区 */

/* ================================================================
 *  RingBuf_Init — 初始化环形队列并注册帧处理回调
 * ================================================================ */
void RingBuf_Init(RingBuf_FrameHandler handler)
{
    rb_handler  = handler;
    rb_head     = 0;
    rb_tail     = 0;
    rb_count    = 0;
    rb_recv_idx = 0;
}
/**
 *  变量说明:
 *  ┌──────────────────────┬────────────────────────────────────────┬──────────────────┐
 *  │ 变量                 │ 作用                                   │ 来源             │
 *  ├──────────────────────┼────────────────────────────────────────┼──────────────────┤
 *  │ handler              │ 用户注册的帧处理回调函数指针           │ 调用者传入       │
 *  │ rb_handler           │ 内部存储的回调函数指针                 │ 本文件定义       │
 *  │ rb_head/rb_tail      │ 环形队列头尾指针                       │ 本文件定义       │
 *  │ rb_count             │ 环形队列当前帧数                       │ 本文件定义       │
 *  │ rb_recv_idx          │ 字节拼接缓冲区写入位置                 │ 本文件定义       │
 *  └──────────────────────┴────────────────────────────────────────┴──────────────────┘
 */

/* ================================================================
 *  RingBuf_FeedByte — ISR 逐字节喂入 (极轻量, 不阻塞)
 *
 *  在 ISR 中每收到一个字节调用一次
 *  遇到分隔符 \r / \n 或缓冲区满时完结当前帧并推入环形队列
 *  兼容 Windows(\r\n) / Linux(\n) / Mac(\r) 三种行尾
 *  队列满时静默丢弃, 不阻塞 ISR
 * ================================================================ */
void RingBuf_FeedByte(uint8 ch)
{
    /* \r 和 \n 均视为帧分隔符; 溢出也触发封帧 */
    if (ch == '\r' || ch == RINGBUF_DELIMITER || rb_recv_idx >= RINGBUF_FRAME_LEN - 1) {
        rb_recv_buf[rb_recv_idx] = '\0';
        rb_recv_idx = 0;

        /* 只有非空帧才入队 (过滤空行) */
        if (rb_recv_buf[0] != '\0' && rb_count < RINGBUF_CAPACITY) {
            memcpy(rb_queue[rb_head].data, rb_recv_buf, RINGBUF_FRAME_LEN);
            rb_head = (rb_head + 1) % RINGBUF_CAPACITY;
            rb_count++;
        }

        /* 溢出触发的封帧: 当前字节既不是 \r 也不是 \n,
           它属于下一帧的第一个字节, 不可丢弃 */
        if (ch != '\r' && ch != RINGBUF_DELIMITER) {
            rb_recv_buf[rb_recv_idx++] = (char)ch;
        }
        return;
    }

    /* 正常字节: 追加到拼接缓冲 */
    rb_recv_buf[rb_recv_idx++] = (char)ch;
}
